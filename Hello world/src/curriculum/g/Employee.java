package curriculum.g;

public class Employee {

	private String employeeld;
		
	private String name;
	
	public void setEmployeeld(String id) {
		this.employeeld = id;
	}
	
	public String getEmployeeld() {
		return employeeld;
	}
	
	public void setName(String name) {
		this.name = name;
	}
	
	public String getName() {
		return name;
	}

}
